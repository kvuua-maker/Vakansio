function ensureContentJobs(db) {
  const owner = db.prepare("SELECT id, email FROM users WHERE lower(email) = 'kvuua@yahoo.com'").get();
  if (!owner) return 0;
  let inserted = 0;
  const statement = db.prepare(
    `INSERT OR IGNORE INTO jobs (
      id, employer_id, title, company_name, description, summary,
      salary_min, salary_max, city, category, is_remote,
      employment_type, experience, requirements, benefits, contact_email,
      status, verified, company_verified, ai_verified, source, created_at
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'active', 0, 0, 0, 'internal', ?)`
  );
  JOBS.forEach((job, index) => {
    const createdAt = new Date(Date.now() - index * 60 * 60 * 1000).toISOString();
    const result = statement.run(
      job.id,
      owner.id,
      job.title,
      job.company,
      job.description,
      job.description.slice(0, 160),
      job.salaryMin,
      job.salaryMax,
      job.city,
      job.category,
      job.remote ? 1 : 0,
      job.employment,
      job.experience,
      JSON.stringify(job.requirements),
      JSON.stringify(job.benefits),
      owner.email || '',
      createdAt
    );
    inserted += Number(result.changes || 0);
  });
  return inserted;
}

module.exports = { ensureContentJobs, JOBS };
